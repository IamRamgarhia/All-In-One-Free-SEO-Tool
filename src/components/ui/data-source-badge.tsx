/**
 * Where a number came from, said out loud.
 *
 * The standing rule from the August audit is that a number shown to a
 * user needs provenance: where it came from, how fresh, how confident.
 * That rule got applied to AI-visibility rows and then to rankings, and
 * nowhere else — so a health score derived from our own crawler, a
 * traffic figure straight from Google, and an estimate we computed from
 * a heuristic all rendered as the same confident bold number.
 *
 * They are not the same. An agency puts these in a client report, and
 * the difference between "Google says 4,182 clicks" and "we estimate
 * roughly 4,000 sessions" is the difference between a defensible claim
 * and one that falls apart when the client checks.
 *
 * This is the shared vocabulary. One place, so the labels can't drift —
 * CLAUDE.md's fourth standing rule is never to add a second hardcoded
 * list of something that already exists, and every such pair in this
 * codebase had already drifted by the time it was found.
 */

