export function DataSourceBadge({
  source,
  /** ISO date or date the figure DESCRIBES — not when it was fetched. */
  asOf,
  /** Extra context appended to the tooltip, e.g. "across 1,204 impressions". */
  note,
  className,
}: {
  source: DataSource | null | undefined;
  asOf?: string | Date | null;
  note?: string;
  className?: string;
}) {
  if (!source) return null;
  const meta = META[source];
  if (!meta) return null;
  const Icon = meta.icon;

  const asOfLabel = asOf
    ? typeof asOf === "string"
      ? asOf.slice(0, 10)
      : asOf.toISOString().slice(0, 10)
    : null;

  return (
    <span
      title={[meta.detail, note, asOfLabel ? `Figures for ${asOfLabel}.` : null]
        .filter(Boolean)
        .join(" ")}
      className={`inline-flex items-center gap-1 rounded-full px-1.5 py-0.5 text-[10px] font-medium ring-1 ring-inset ${meta.tone} ${className ?? ""}`}
    >
      <Icon className="size-2.5" />
      {meta.label}
      {asOfLabel && <span className="opacity-70">· {asOfLabel}</span>}
    </span>
  );
}

/** The label alone, for places too tight for a badge. */
export function dataSourceLabel(source: DataSource): string {
  return META[source]?.label ?? source;
}

export function dataSourceDetail(source: DataSource): string {
  return META[source]?.detail ?? "";
}

