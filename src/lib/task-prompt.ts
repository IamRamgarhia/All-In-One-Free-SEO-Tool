/**
 * The prompt for fixing a client's site with a coding assistant, by hand:
 * copied from the Tasks page or downloaded as a .md, then pasted into
 * whatever assistant the person uses in VS Code (or in a terminal) on the
 * client's code. No program runs on this machine for it.
 *
 * Also the first message of a Claude Code chat (lib/task-chat), so the
 * manual path and the automatic one ask for exactly the same work.
 *
 * Pure on purpose: easy to test, usable from a route or a server page.
 * Based on the original author's task brief (task-brief.ts in 096f1c9),
 * in French and English, without the MCP tools this fork does not have:
 * the person marks the task done in the app once they have checked it.
 *
 * Kept apart from the audit page's own "copy the instructions" work: this
 * file is about tasks and whole audits handed to a coding assistant.
 */

import type { TaskPage } from "@/lib/task-pages";

export type PromptLocale = "fr" | "en";

export function promptLocale(locale: string | null | undefined): PromptLocale {
  return locale?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export type PromptClient = {
  name: string;
  url: string;
  techStack?: string[] | null;
  localPath?: string | null;
  githubRepo?: string | null;
  baseBranch?: string | null;
};

export type TaskPromptInput = {
  task: {
    id: number;
    title: string;
    description?: string | null;
    whyItMatters?: string | null;
    priority: string;
    pages?: TaskPage[] | null;
  };
  client: PromptClient;
  locale: string;
};

