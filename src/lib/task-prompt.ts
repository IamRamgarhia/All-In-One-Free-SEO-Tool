export type AuditPromptInput = {
  /** The audited URL. */
  url: string;
  client: PromptClient;
  /** The audit's LLM export (renderLlmReport), the same text as "Export LLM". */
  report: string;
  locale: string;
};

export function buildAuditPrompt({ url, client, report, locale }: AuditPromptInput): string {
  const l = promptLocale(locale);
  const A = AUDIT_TEXT[l];
  const lines: string[] = [A.heading(url), ""];
  header(lines, client, l);
  lines.push("", A.intro);
  workRules(lines, client, l);
  lines.push("", A.check, ...A.checkItems);
  lines.push("", A.end, A.endText);
  const head = lines.join("\n");
  // The report is the engine's own text: left exactly as exported.
  return `${l === "fr" ? frenchSpaces(head) : head}\n\n${A.report}\n\n${report.trim()}\n`;
}

/** File name for the downloaded prompt. */
export function promptFileName(kind: "task" | "audit", id: number): string {
  return `${kind === "task" ? "tache" : "audit"}-${id}.prompt.md`;
}
