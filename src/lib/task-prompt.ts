function header(lines: string[], client: PromptClient, l: PromptLocale) {
  const T = TEXT[l];
  lines.push(label(T.site, `${client.name} (${client.url})`, l));
  if (client.techStack?.length) lines.push(label(T.stack, client.techStack.join(", "), l));
  if (client.localPath) lines.push(label(T.folder, client.localPath, l));
  if (client.githubRepo) lines.push(label(T.repo, client.githubRepo, l));
}

/** "Label : value" with the French non-breaking space, "Label: value" in English. */
function label(name: string, value: string, l: PromptLocale): string {
  return l === "fr" ? `${name} : ${value}` : `${name}: ${value}`;
}

function frenchSpaces(s: string): string {
  // A non-breaking space before the high punctuation, as French typography wants.
  return s.replace(/ ([:;?!])/g, " $1");
}

function workRules(lines: string[], client: PromptClient, l: PromptLocale) {
  const T = TEXT[l];
  lines.push("", T.how);
  lines.push(client.localPath ? T.inFolder(client.localPath) : T.noFolder);
  lines.push(T.readFirst, T.noDeploy);
  if (client.githubRepo) lines.push(T.branch(client.baseBranch || "main"));
  lines.push(T.docs);
}

export function buildTaskPrompt({ task, client, locale }: TaskPromptInput): string {
  const l = promptLocale(locale);
  const T = TEXT[l];
  const lines: string[] = [T.heading(task.title.trim()), ""];
  header(lines, client, l);
  lines.push(label(T.priority, T.priorities[task.priority] ?? task.priority, l));

  if (task.description?.trim()) lines.push("", T.what, task.description.trim());
  if (task.whyItMatters?.trim()) lines.push("", T.why, task.whyItMatters.trim());

  const pages = openPages(task.pages);
  if (pages.length) {
    lines.push("", T.pages, ...pages.slice(0, MAX_PAGES).map((u) => `- ${u}`));
    if (pages.length > MAX_PAGES) lines.push(T.morePages(pages.length - MAX_PAGES));
  }

  const hints = stackHintsFor(client.techStack).flatMap((h) => h.hints[l]);
  if (hints.length) lines.push("", T.where, ...hints.map((h) => `- ${h}`));

  workRules(lines, client, l);

  lines.push("", T.check);
  lines.push(pages.length ? T.checkPages : T.checkUrl(client.url));
  lines.push(T.checkBuild, T.checkDiff);

  lines.push("", T.end, T.endText(task.id));
  const out = lines.join("\n") + "\n";
  return l === "fr" ? frenchSpaces(out) : out;
}

