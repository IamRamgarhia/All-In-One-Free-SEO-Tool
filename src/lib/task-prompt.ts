export function stackHintsFor(techStack?: string[] | null): StackHint[] {
  const stack = techStack ?? [];
  return STACK_HINTS.filter((h) => stack.some((t) => h.match.test(t)));
}

/** The pages still to fix: the ticked ones are done. */
export function openPages(pages?: TaskPage[] | null): string[] {
  return (pages ?? []).filter((p) => !p.done && p.url.trim()).map((p) => p.url.trim());
}

