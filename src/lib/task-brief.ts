/**
 * The prompt handed to a coding assistant (Claude Code, Cursor, Codex...)
 * for one SEO task: what to do, why, on which site, and — when the client
 * has a local project folder — where to do it.
 *
 * Pure on purpose: the MCP tools build it today, a "copy for AI" button
 * can reuse it, and it is easy to test.
 */

export type TaskBriefInput = {
  task: {
    id: number;
    title: string;
    description?: string | null;
    whyItMatters?: string | null;
    priority: string;
    toolPath?: string | null;
  };
  client: {
    name: string;
    url: string;
    techStack?: string[] | null;
    localPath?: string | null;
  };
};

type StackHint = { match: RegExp; label: string; hints: string[] };

/**
 * Where such things usually live in each stack. These are starting points
 * for a search, worded as such — a project is free to differ and the
 * assistant has to look.
 */
const STACK_HINTS: StackHint[] = [
  {
    match: /astro/i,
    label: "Astro",
    hints: [
      "Pages are usually in src/pages/*.astro; shared <head> and layout in src/layouts/.",
      "A sitemap is either a hand-written public/sitemap.xml or generated by @astrojs/sitemap at build time (check astro.config.*); never edit dist/.",
      "robots.txt, llms.txt and verification files live in public/.",
    ],
  },
  {
    match: /next/i,
    label: "Next.js",
    hints: [
      "Routes are in app/ or pages/; metadata via the Metadata API or <Head>.",
      "Sitemap and robots are often app/sitemap.ts and app/robots.ts, or static files in public/.",
    ],
  },
  {
    match: /wordpress|woocommerce/i,
    label: "WordPress",
    hints: [
      "Content and settings live in the CMS, not in this folder; a theme or plugin folder here only holds code.",
      "Prefer the SEO tool's own fix tools for titles and meta over editing theme files.",
    ],
  },
];

export function stackHintsFor(techStack?: string[] | null): StackHint[] {
  const stack = techStack ?? [];
  return STACK_HINTS.filter((h) => stack.some((t) => h.match.test(t)));
}

export function buildTaskBrief({ task, client }: TaskBriefInput): string {
  const lines: string[] = [];
  lines.push(`# SEO task: ${task.title}`);
  lines.push("");
  lines.push(`Site: ${client.name} (${client.url})`);
  lines.push(`Priority: ${task.priority}`);
  if (client.techStack?.length) {
    lines.push(`Stack: ${client.techStack.join(", ")}`);
  }
  if (client.localPath) {
    lines.push(`Project folder: ${client.localPath}`);
  }
  if (task.description?.trim()) {
    lines.push("", "## What to do", task.description.trim());
  }
  if (task.whyItMatters?.trim()) {
    lines.push("", "## Why it matters", task.whyItMatters.trim());
  }

  const hints = stackHints(client.techStack);
  if (hints.length) {
    lines.push("", "## Where to look (typical, verify in the project)");
    lines.push(...hints.map((h) => `- ${h}`));
  }

  lines.push("", "## How to work");
  if (client.localPath) {
    lines.push(
      `- Work inside ${client.localPath}. Do not touch other folders.`,
    );
  } else {
    lines.push(
      "- This client has no project folder set. Ask where the site source is before editing anything.",
    );
  }
  lines.push(
    "- Read the relevant files first; make the smallest change that completes the task.",
    "- Do not publish or deploy. Leave the changes for review and say what you changed.",
    `- When it is done and verified, mark task ${task.id} done with the update_task tool.`,
  );
  return lines.join("\n") + "\n";
}

function stackHints(techStack?: string[] | null): string[] {
  return stackHintsFor(techStack).flatMap((h) => h.hints);
}
