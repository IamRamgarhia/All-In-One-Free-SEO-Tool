function stb_get_meta_description(int $post_id): string
{
    // Try the SEO plugins in priority order
    $candidates = [
        '_yoast_wpseo_metadesc',          // Yoast
        'rank_math_description',           // Rank Math
        '_aioseop_description',            // All in One SEO (legacy)
        '_aioseo_description',             // All in One SEO (current)
    ];
    foreach ($candidates as $key) {
        $val = get_post_meta($post_id, $key, true);
        if (!empty($val)) {
            return (string)$val;
        }
    }
    return '';
}

function stb_set_meta_description(int $post_id, string $value): void
{
    // Write to all known plugins so it sticks regardless of which one is active
    update_post_meta($post_id, '_yoast_wpseo_metadesc', $value);
    update_post_meta($post_id, 'rank_math_description', $value);
    update_post_meta($post_id, '_aioseo_description', $value);
}

/**
 * Canonical URL, read from whichever SEO plugin is present.
 *
 * Same priority order as the description, for the same reason: a site
 * with two SEO plugins installed has one of them actually rendering the
 * tag, and we cannot know which, so we read the first that has a value
 * and write all of them.
 */
function stb_get_canonical(int $post_id): string
{
    $candidates = [
        '_yoast_wpseo_canonical',
        'rank_math_canonical_url',
        '_aioseo_canonical_url',
    ];
    foreach ($candidates as $key) {
        $val = get_post_meta($post_id, $key, true);
        if (!empty($val)) {
            return (string)$val;
        }
    }
    return '';
}

function stb_set_canonical(int $post_id, string $value): void
{
    update_post_meta($post_id, '_yoast_wpseo_canonical', $value);
    update_post_meta($post_id, 'rank_math_canonical_url', $value);
    update_post_meta($post_id, '_aioseo_canonical_url', $value);
}

/**
 * The robots meta directive for one post — "index,follow" and friends.
 *
 * Yoast splits this across two keys holding 0/1/2 sentinels, Rank Math
 * stores an array of tokens. Both are normalised to the comma string the
 * caller sent, so what goes out matches what comes back.
 */
function stb_get_robots_meta(int $post_id): string
{
    $rm = get_post_meta($post_id, 'rank_math_robots', true);
    if (is_array($rm) && $rm) {
        return implode(',', array_map('strval', $rm));
    }
    $noindex = get_post_meta($post_id, '_yoast_wpseo_meta-robots-noindex', true);
    $nofollow = get_post_meta($post_id, '_yoast_wpseo_meta-robots-nofollow', true);
    if ($noindex === '' && $nofollow === '') {
        return '';
    }
    // Yoast: '1' means noindex, '2' means index, '' means default.
    $parts = [];
    $parts[] = ($noindex === '1') ? 'noindex' : 'index';
    $parts[] = ($nofollow === '1') ? 'nofollow' : 'follow';
    return implode(',', $parts);
}

function stb_set_robots_meta(int $post_id, string $value): void
{
    $tokens = array_filter(array_map('trim', explode(',', strtolower($value))));
    $noindex = in_array('noindex', $tokens, true);
    $nofollow = in_array('nofollow', $tokens, true);

    update_post_meta($post_id, '_yoast_wpseo_meta-robots-noindex', $noindex ? '1' : '2');
    update_post_meta($post_id, '_yoast_wpseo_meta-robots-nofollow', $nofollow ? '1' : '');
    update_post_meta($post_id, 'rank_math_robots', array_values($tokens));
}

function stb_record_revision(string $field, string $object, $old, $new): int
{
    $revs = get_option(STB_OPTION_REVISIONS, []);

    // Monotonic, taken from the highest id ever issued — NOT count() + 1.
    //
    // The list is capped at the most recent 500, so once a site passed
    // 500 changes count() stayed at 500 and every revision from then on
    // was id 501. /undo/501 then found the OLDEST 501 and restored a
    // value from hundreds of edits ago, to a live site, reporting
    // success. A busy site would hit this in a week.
    $highest = 0;
    foreach ($revs as $r) {
        $id = (int)($r['rev_id'] ?? 0);
        if ($id > $highest) {
            $highest = $id;
        }
    }
    $rev_id = $highest + 1;

    $revs[] = [
        'rev_id' => $rev_id,
        'ts' => time(),
        'field' => $field,
        'object' => $object,
        'old' => $old,
        'new' => $new,
    ];
    // Cap at last 500 to keep options table small
    if (count($revs) > 500) {
        $revs = array_slice($revs, -500);
    }
    update_option(STB_OPTION_REVISIONS, $revs);
    return $rev_id;
}

function stb_rest_get_post_seo(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    $post = get_post($id);
    if (!$post) {
        return new WP_REST_Response(['ok' => false, 'error' => 'Post not found'], 404);
    }
    return new WP_REST_Response([
        'ok' => true,
        'id' => $id,
        'title' => $post->post_title,
        'meta_description' => stb_get_meta_description($id),
        // Returned so the caller can see the current value before
        // changing it. The client's PostSeo type has carried these two
        // fields since it was written and this handler returned neither,
        // so both were always null — which reads as "this page has no
        // canonical" for every page on every site.
        'canonical' => stb_get_canonical($id),
        'robots' => stb_get_robots_meta($id),
        'permalink' => get_permalink($id),
        'status' => $post->post_status,
        'modified' => $post->post_modified,
    ]);
}

function stb_rest_update_post_seo(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    $post = get_post($id);
    if (!$post) {
        return new WP_REST_Response(['ok' => false, 'error' => 'Post not found'], 404);
    }
    $body = $req->get_json_params() ?: [];
    $changes = [];

    if (isset($body['title'])) {
        $new = sanitize_text_field($body['title']);
        $old = $post->post_title;
        if ($new !== $old) {
            wp_update_post(['ID' => $id, 'post_title' => $new]);
            $rev_id = stb_record_revision('title', "post:$id", $old, $new);
            $changes[] = ['field' => 'title', 'rev_id' => $rev_id];
        }
    }

    if (isset($body['meta_description'])) {
        $new = sanitize_text_field($body['meta_description']);
        $old = stb_get_meta_description($id);
        if ($new !== $old) {
            stb_set_meta_description($id, $new);
            $rev_id = stb_record_revision('meta_description', "post:$id", $old, $new);
            $changes[] = ['field' => 'meta_description', 'rev_id' => $rev_id];
        }
    }

    // Canonical and robots.
    //
    // Both of these were in the TypeScript client's type from the
    // beginning and this handler read neither, so a canonical sent here
    // was accepted, ignored, and answered {ok:true} — a write that
    // reported success and changed nothing. The client had to grow an
    // explicit refusal to stop two "apply fix" buttons lying. That
    // refusal comes out in the same change as this.
    if (isset($body['canonical'])) {
        $new = esc_url_raw(trim((string)$body['canonical']));
        $old = stb_get_canonical($id);
        if ($new !== $old) {
            stb_set_canonical($id, $new);
            $rev_id = stb_record_revision('canonical', "post:$id", $old, $new);
            $changes[] = ['field' => 'canonical', 'rev_id' => $rev_id];
        }
    }

    if (isset($body['robots'])) {
        $new = sanitize_text_field($body['robots']);
        $old = stb_get_robots_meta($id);
        if ($new !== $old) {
            stb_set_robots_meta($id, $new);
            $rev_id = stb_record_revision('robots', "post:$id", $old, $new);
            $changes[] = ['field' => 'robots', 'rev_id' => $rev_id];
        }
    }

    return new WP_REST_Response(['ok' => true, 'changes' => $changes]);
}

function stb_rest_update_alt(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    $post = get_post($id);
    if (!$post || $post->post_type !== 'attachment') {
        return new WP_REST_Response(['ok' => false, 'error' => 'Attachment not found'], 404);
    }
    $body = $req->get_json_params() ?: [];
    $new = isset($body['alt']) ? sanitize_text_field($body['alt']) : '';
    $old = (string)get_post_meta($id, '_wp_attachment_image_alt', true);

    $rev_id = null;
    if ($new !== $old) {
        update_post_meta($id, '_wp_attachment_image_alt', $new);
        $rev_id = stb_record_revision('alt', "attachment:$id", $old, $new);
    }

    // The attachment's alt is only half the job, and for most sites it is
    // the half that does not show.
    //
    // The block editor writes the <img> straight into post_content with
    // its own alt attribute baked in. wp_get_attachment_image() reads the
    // attachment meta; an inline <img> does not. So updating the meta
    // alone stored the text, answered {ok: true}, read back correctly
    // through this plugin's own /images endpoint — and left the page
    // serving alt="". Verified on a real WordPress: the finding was
    // reported fixed and the page was unchanged.
    $content_changes = stb_apply_alt_to_content($id, $new);

    return new WP_REST_Response([
        'ok' => true,
        'rev_id' => $rev_id,
        'posts_updated' => $content_changes,
        'note' => ($rev_id === null && !$content_changes) ? 'no change' : null,
    ]);
}

/**
 * Rewrite the alt attribute on inline <img> tags for one attachment.
 *
 * Matched by the wp-image-N class WordPress puts on every image it
 * inserts, so this can only ever touch images that genuinely are this
 * attachment. Nothing else about the tag is altered — not the src, not
 * the classes, not the dimensions — because the goal is one attribute
 * and anything broader is a way to damage a page while fixing it.
 *
 * The whole previous post_content is recorded, so undo is a straight
 * put-it-back rather than an attempt to unpick individual edits. That is
 * the same approach the internal-link inserter takes, for the same
 * reason.
 *
 * Returns how many posts were changed.
 */
function stb_apply_alt_to_content(int $attachment_id, string $alt): int
{
    global $wpdb;

    $needle = 'wp-image-' . $attachment_id;
    $posts = $wpdb->get_results(
        $wpdb->prepare(
            "SELECT ID, post_content FROM {$wpdb->posts}
             WHERE post_status NOT IN ('trash', 'auto-draft')
               AND post_type NOT IN ('revision', 'attachment')
               AND post_content LIKE %s
             LIMIT 20",
            '%' . $wpdb->esc_like($needle) . '%',
        ),
    );
    if (!$posts) {
        return 0;
    }

    $changed = 0;
    foreach ($posts as $row) {
        $before = (string)$row->post_content;
        $after = stb_rewrite_img_alt($before, $attachment_id, $alt);
        if ($after === $before) {
            continue;
        }
        wp_update_post(['ID' => (int)$row->ID, 'post_content' => $after]);
        stb_record_revision('content', 'post:' . (int)$row->ID, $before, $after);
        $changed++;
    }
    return $changed;
}

/**
 * Set alt="..." on every <img> carrying this attachment's class.
 *
 * Deliberately string surgery on the one tag rather than a DOM parse of
 * the whole document: loading post_content into DOMDocument and writing
 * it back reformats markup the author wrote by hand, mangles block
 * comments, and turns a one-attribute change into a whole-file diff.
 */
function stb_rewrite_img_alt(string $content, int $attachment_id, string $alt): string
{
    $class = 'wp-image-' . $attachment_id;
    $escaped = esc_attr($alt);

    return (string)preg_replace_callback(
        '#<img\b[^>]*>#i',
        static function (array $m) use ($class, $escaped): string {
            $tag = $m[0];
            // Only this attachment's images. The class check is on a word
            // boundary so wp-image-6 never matches wp-image-60.
            if (!preg_match('#\bclass\s*=\s*("|\')([^"\']*)\1#i', $tag, $c)) {
                return $tag;
            }
            if (!preg_match('#(^|\s)' . preg_quote($class, '#') . '(\s|$)#', $c[2])) {
                return $tag;
            }
            if (preg_match('#\balt\s*=\s*("|\')[^"\']*\1#i', $tag)) {
                return (string)preg_replace(
                    '#\balt\s*=\s*("|\')[^"\']*\1#i',
                    'alt="' . $escaped . '"',
                    $tag,
                    1,
                );
            }
            // No alt attribute at all — add one just before the close.
            return (string)preg_replace(
                '#\s*(/?)>$#',
                ' alt="' . $escaped . '"$1>',
                $tag,
                1,
            );
        },
        $content,
    );
}

function stb_rest_set_schema(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    $body = $req->get_json_params() ?: [];
    // IMPORTANT: do NOT run wp_kses_post() on JSON-LD. It's an HTML
    // sanitizer that strips characters that are legitimate inside JSON
    // string values (<, >, &), producing invalid JSON. Instead, validate
    // that the input is well-formed JSON via json_decode().
    $jsonld_raw = isset($body['jsonld']) ? (string)$body['jsonld'] : '';

    // Empty means REMOVE the markup, and must not be an error.
    //
    // The only audit finding that triggers a schema write is
    // missing_schema, so the previous value the SEO Tool records is
    // always the empty string — and undo replays that previous value.
    // Rejecting it meant the tool could add structured data to a page
    // and then had no way to take it off again, while its own rule is
    // that it never writes anything it can't undo.
    //
    // Deletes the meta rather than storing '' so the front-end filter
    // that prints the <script> tag sees nothing at all.
    if ($jsonld_raw === '') {
        $old = (string)get_post_meta($id, '_stb_schema_jsonld', true);
        if ($old === '') {
            return new WP_REST_Response(['ok' => true, 'rev_id' => null, 'note' => 'no change']);
        }
        delete_post_meta($id, '_stb_schema_jsonld');
        $rev_id = stb_record_revision('schema', "post:$id", $old, '');
        return new WP_REST_Response(['ok' => true, 'rev_id' => $rev_id, 'removed' => true]);
    }

    $decoded = json_decode($jsonld_raw, true);
    if ($decoded === null) {
        // Both branches end up here, and both are handled above or
        // rejected here — deliberately, because the old code let the
        // literal string "null" through as "valid JSON". It is, but
        // wp_json_encode(null) is "null", which is not empty, so the
        // head filter printed <script type="application/ld+json">null
        // </script> onto the page: markup that validators reject and
        // that makes the page look marked up when it isn't.
        if (strtolower(trim($jsonld_raw)) === 'null') {
            return new WP_REST_Response(
                [
                    'ok' => false,
                    'error' => 'jsonld cannot be null — send an empty string to remove the markup instead',
                ],
                400,
            );
        }
        return new WP_REST_Response(
            ['ok' => false, 'error' => 'jsonld must be valid JSON'],
            400,
        );
    }

    // Scalars decode fine and are not structured data. "42" or "\"hi\""
    // would be stored and printed as a JSON-LD block that means nothing.
    if (!is_array($decoded)) {
        return new WP_REST_Response(
            ['ok' => false, 'error' => 'jsonld must be a JSON object or array'],
            400,
        );
    }
    // Re-encode for canonical form, also flags edge-case unicode.
    $jsonld = wp_json_encode($decoded, JSON_UNESCAPED_SLASHES);
    if ($jsonld === false) {
        return new WP_REST_Response(
            ['ok' => false, 'error' => 'jsonld could not be re-encoded'],
            400,
        );
    }
    $old = (string)get_post_meta($id, '_stb_schema_jsonld', true);
    update_post_meta($id, '_stb_schema_jsonld', $jsonld);
    $rev_id = stb_record_revision('schema', "post:$id", $old, $jsonld);
    return new WP_REST_Response(['ok' => true, 'rev_id' => $rev_id]);
}

/**
 * Read the JSON-LD we previously wrote for a post.
 *
 * Returns only markup this plugin manages — schema output by Yoast,
 * Rank Math or a theme is deliberately NOT reported, because the SEO
 * Tool uses this to decide whether it may overwrite, and claiming
 * ownership of another plugin's markup would let it destroy that.
 *
 * An empty string means "we have written none", not "this page has
 * none". The distinction matters and the field name says so.
 */
function stb_rest_get_schema(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    if (!get_post($id)) {
        return new WP_REST_Response(['ok' => false, 'error' => 'No such post'], 404);
    }
    return new WP_REST_Response([
        'ok' => true,
        'managedJsonLd' => (string)get_post_meta($id, '_stb_schema_jsonld', true),
    ]);
}

/**
 * Every image on a post, with the attachment id needed to set alt text.
 *
 * Two sources, because neither is complete on its own: the media library
 * knows about attachments uploaded to the post, and the content itself
 * knows about images inserted from elsewhere. WordPress marks the latter
 * with a `wp-image-{id}` class, which is how we recover the id for an
 * image the post doesn't "own".
 *
 * Images we can't resolve to an attachment are returned with a null id
 * and reported honestly rather than dropped — the SEO Tool shows them as
 * "found, can't fix automatically" instead of pretending they don't
 * exist.
 */
function stb_rest_list_post_images(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    $post = get_post($id);
    if (!$post) {
        return new WP_REST_Response(['ok' => false, 'error' => 'No such post'], 404);
    }

    $images = [];
    $seen = [];

    $add = function (?int $att_id, string $src) use (&$images, &$seen) {
        $key = $att_id ? "id:$att_id" : "src:$src";
        if (isset($seen[$key])) {
            return;
        }
        $seen[$key] = true;
        $images[] = [
            'attachmentId' => $att_id,
            'src' => $src,
            'alt' => $att_id
                ? (string)get_post_meta($att_id, '_wp_attachment_image_alt', true)
                : '',
            // The tool needs to know an id-less image is unfixable rather
            // than merely un-alt-texted.
            'fixable' => $att_id !== null,
        ];
    };

    // Featured image first — it's the one most likely to be missing alt
    // text and the most visible when it is.
    $thumb_id = (int)get_post_thumbnail_id($id);
    if ($thumb_id > 0) {
        $add($thumb_id, (string)wp_get_attachment_url($thumb_id));
    }

    // Attachments uploaded to this post.
    foreach (get_attached_media('image', $id) as $att) {
        $add((int)$att->ID, (string)wp_get_attachment_url($att->ID));
    }

    // Images in the content, including ones from the media library that
    // were never "attached" to this post.
    if (preg_match_all('/<img[^>]+>/i', (string)$post->post_content, $tags)) {
        foreach ($tags[0] as $tag) {
            if (!preg_match('/\ssrc=["\']([^"\']+)["\']/i', $tag, $m)) {
                continue;
            }
            $src = $m[1];
            $att_id = null;
            if (preg_match('/wp-image-(\d+)/', $tag, $cm)) {
                $att_id = (int)$cm[1];
            } else {
                $guess = attachment_url_to_postid($src);
                if ($guess > 0) {
                    $att_id = $guess;
                }
            }
            $add($att_id, $src);
        }
    }

    return new WP_REST_Response(['ok' => true, 'images' => $images]);
}

/**
 * Insert internal links into a post's body.
 *
 * The only endpoint here that edits post_content rather than a metadata
 * field, and it is treated accordingly. A bad write damages the article,
 * not a tag — so:
 *
 *  - Anchors are matched in VISIBLE TEXT ONLY. The content is split on
 *    tags and only the text between them is searched, so an anchor can
 *    never be matched inside an attribute, a URL, a script, or the text
 *    of an existing link. Naive str_replace on HTML would happily turn
 *    `<a href="/x">pricing</a>` into nested anchors and corrupt the
 *    markup.
 *  - First occurrence only, once per anchor. Linking every mention of a
 *    word is the behaviour that gets auto-linking plugins uninstalled.
 *  - Skips anchors already linked anywhere in the post, so re-running
 *    can't stack links on the same phrase.
 *  - The ENTIRE previous post_content is stored as the revision, so undo
 *    restores the article exactly rather than trying to unpick edits.
 */
function stb_rest_insert_links(WP_REST_Request $req): WP_REST_Response
{
    $id = (int)$req['id'];
    $post = get_post($id);
    if (!$post) {
        return new WP_REST_Response(['ok' => false, 'error' => 'No such post'], 404);
    }

    $body = $req->get_json_params() ?: [];
    $links = isset($body['links']) && is_array($body['links']) ? $body['links'] : [];
    if (!$links) {
        return new WP_REST_Response(['ok' => false, 'error' => 'links required'], 400);
    }
    // A cap the caller cannot exceed. Ten new links in one pass is
    // already a lot for one article; more reads as spam to a person and
    // to Google.
    if (count($links) > 10) {
        $links = array_slice($links, 0, 10);
    }

    $original = (string)$post->post_content;
    $content = $original;
    $inserted = [];
    $skipped = [];

    foreach ($links as $link) {
        $anchor = trim((string)($link['anchor'] ?? ''));
        $url = trim((string)($link['url'] ?? ''));
        if ($anchor === '' || $url === '') {
            continue;
        }
        // Only same-site URLs. This endpoint exists for internal linking;
        // letting it write arbitrary external hrefs would turn a
        // connection key into a link-injection vector.
        if (!stb_is_internal_url($url)) {
            $skipped[] = ['anchor' => $anchor, 'reason' => 'not an internal URL'];
            continue;
        }
        if (mb_strlen($anchor) < 3 || mb_strlen($anchor) > 80) {
            $skipped[] = ['anchor' => $anchor, 'reason' => 'anchor length'];
            continue;
        }
        // Already linked somewhere in the post — leave it alone.
        if (stb_anchor_is_linked($content, $anchor)) {
            $skipped[] = ['anchor' => $anchor, 'reason' => 'already linked'];
            continue;
        }

        $replaced = stb_link_first_text_occurrence($content, $anchor, $url);
        if ($replaced === null) {
            $skipped[] = ['anchor' => $anchor, 'reason' => 'anchor not found in visible text'];
            continue;
        }
        $content = $replaced;
        $inserted[] = ['anchor' => $anchor, 'url' => $url];
    }

    if (!$inserted) {
        return new WP_REST_Response([
            'ok' => true,
            'inserted' => [],
            'skipped' => $skipped,
            'changed' => false,
        ]);
    }

    $res = wp_update_post(['ID' => $id, 'post_content' => $content], true);
    if (is_wp_error($res)) {
        return new WP_REST_Response(
            ['ok' => false, 'error' => $res->get_error_message()],
            500,
        );
    }

    // Whole-body revision. Undo restores the article exactly.
    $rev_id = stb_record_revision('content', "post:$id", $original, $content);

    return new WP_REST_Response([
        'ok' => true,
        'inserted' => $inserted,
        'skipped' => $skipped,
        'changed' => true,
        'rev_id' => $rev_id,
    ]);
}

/** Same-host check. Relative paths are internal by definition. */
function stb_is_internal_url(string $url): bool
{
    if (str_starts_with($url, '/') && !str_starts_with($url, '//')) {
        return true;
    }
    $host = parse_url($url, PHP_URL_HOST);
    if (!$host) {
        return false;
    }
    $home = parse_url(home_url(), PHP_URL_HOST);
    return strtolower($host) === strtolower((string)$home);
}

/**
 * Is this anchor phrase already inside a link somewhere in the content?
 *
 * Walks the markup the same way the inserter does, and answers yes only
 * when the phrase appears in text that is genuinely inside an <a>.
 *
 * This used to be two string tests, and both were wrong:
 *
 *   stripos($content, '>' . $anchor . '<')
 *     True for ANY element whose whole text is the phrase —
 *     <code>pricing</code>, <li>pricing</li>, <strong>pricing</strong>,
 *     <td>pricing</td>. So a phrase that appeared in a list or a table
 *     anywhere on the page could never be linked, and the tool answered
 *     "already linked", which was simply untrue. Nothing errored; the
 *     work was silently skipped with a wrong explanation.
 *
 *   preg_match('/<a[^>]*>[^<]*' . preg_quote($anchor) . '/i', ...)
 *     Only sees the phrase in an anchor's FIRST text node, so
 *     <a href="/x"><strong>pricing</strong></a> read as not linked, and
 *     the inserter would have been asked to link it a second time.
 *
 * Walking costs one pass over the content and is right in both
 * directions.
 */
function stb_anchor_is_linked(string $content, string $anchor): bool
{
    $parts = preg_split('/(<[^>]+>)/', $content, -1, PREG_SPLIT_DELIM_CAPTURE);
    if ($parts === false) {
        return false;
    }

    $depth = 0;
    foreach ($parts as $part) {
        if ($part === '') {
            continue;
        }
        if ($part[0] === '<') {
            if (preg_match('/^<\s*(\/?)\s*a\b/i', $part, $m)) {
                $depth += $m[1] === '/' ? -1 : 1;
                if ($depth < 0) {
                    $depth = 0;
                }
            }
            continue;
        }
        if ($depth > 0 && mb_stripos($part, $anchor) !== false) {
            return true;
        }
    }

    return false;
}

/**
 * Link the first occurrence of $anchor that appears in visible text.
 *
 * Walks the content splitting on tags, so only the text BETWEEN tags is
 * eligible. Skips anything inside <a>, <script>, <style>, <code>, <pre>
 * — linking a word inside a code sample is worse than not linking it.
 *
 * Returns the new content, or null if the anchor never appears in
 * eligible text.
 */
function stb_link_first_text_occurrence(string $content, string $anchor, string $url): ?string
{
    $parts = preg_split('/(<[^>]+>)/', $content, -1, PREG_SPLIT_DELIM_CAPTURE);
    if ($parts === false) {
        return null;
    }

    $skip_depth = 0;
    $skip_tags = ['a', 'script', 'style', 'code', 'pre', 'h1', 'h2', 'h3'];

    foreach ($parts as $i => $part) {
        if ($part === '') {
            continue;
        }
        if ($part[0] === '<') {
            if (preg_match('/^<\s*(\/?)\s*([a-z0-9]+)/i', $part, $m)) {
                $tag = strtolower($m[2]);
                if (in_array($tag, $skip_tags, true)) {
                    $skip_depth += $m[1] === '/' ? -1 : 1;
                    if ($skip_depth < 0) {
                        $skip_depth = 0;
                    }
                }
            }
            continue;
        }
        if ($skip_depth > 0) {
            continue;
        }

        $pos = mb_stripos($part, $anchor);
        if ($pos === false) {
            continue;
        }

        // Preserve the casing actually used in the text.
        $matched = mb_substr($part, $pos, mb_strlen($anchor));
        $replacement = '<a href="' . esc_url($url) . '">' . esc_html($matched) . '</a>';
        $parts[$i] = mb_substr($part, 0, $pos)
            . $replacement
            . mb_substr($part, $pos + mb_strlen($anchor));

        return implode('', $parts);
    }

    return null;
}

/**
 * Is another SEO plugin responsible for the <head> tags?
 *
 * This decides whether we render a meta description and canonical
 * ourselves. Getting it wrong in one direction prints two canonicals on
 * a page, which is worse than none; getting it wrong in the other means
 * the value we store is never rendered at all.
 *
 * Checked by class/function rather than by plugin file, because a plugin
 * can be installed under any folder name and several of these ship
 * renamed in hosting bundles.
 */
function stb_seo_plugin_active(): bool
{
    return defined('WPSEO_VERSION')            // Yoast
        || class_exists('RankMath')            // Rank Math
        || defined('AIOSEO_VERSION')           // All in One SEO
        || defined('SEOPRESS_VERSION')         // SEOPress
        || class_exists('The_SEO_Framework\\Load'); // The SEO Framework
}

/**
 * Render the description and canonical we were asked to store, when
 * nothing else will.
 *
 * Found by running this plugin on a real WordPress for the first time:
 * on a site with no SEO plugin, writing a meta description stored it in
 * three plugins' meta keys, the REST API read it back correctly, and the
 * page served zero description tags. The canonical was worse — we wrote
 * one pointing elsewhere and WordPress core's own rel_canonical kept
 * winning, so the API reported a change that had no effect on anything
 * Google sees.
 *
 * That is the failure this codebase keeps producing: a write that
 * reports success and changes nothing. It was invisible from inside the
 * app, because every layer up to and including the plugin's own response
 * was telling the truth.
 *
 * Deliberately silent when an SEO plugin is active — that plugin owns
 * these tags, it reads the same meta keys we write, and a second
 * canonical in the head is a real problem rather than a cosmetic one.
 */
add_action('wp_head', 'stb_render_head_tags', 1);
function stb_render_head_tags(): void
{
    if (!is_singular() || stb_seo_plugin_active()) {
        return;
    }
    $id = get_the_ID();
    if (!$id) {
        return;
    }

    $desc = stb_get_meta_description($id);
    if ($desc !== '') {
        echo "\n<!-- SEO Tool -->\n<meta name=\"description\" content=\""
            . esc_attr($desc) . "\" />\n";
    }

    $canonical = stb_get_canonical($id);
    if ($canonical !== '') {
        // Core's rel_canonical runs at priority 10 and would print a
        // second one. Ours is the deliberate value, so core's comes off.
        remove_action('wp_head', 'rel_canonical');
        echo '<link rel="canonical" href="' . esc_url($canonical) . "\" />\n";
    }

    $robots = stb_get_robots_meta($id);
    if ($robots !== '') {
        echo '<meta name="robots" content="' . esc_attr($robots) . "\" />\n";
    }
}

// Hook our schema into <head> on relevant pages
add_action('wp_head', function () {
    if (is_singular()) {
        $jsonld = get_post_meta(get_the_ID(), '_stb_schema_jsonld', true);
        if (!empty($jsonld)) {
            // CRITICAL: escape </script> sequences so an attacker who can
            // POST schema JSON-LD can't break out of the <script> block
            // and inject arbitrary JavaScript. The </script> check must
            // be case-insensitive — `</SCRIPT>` also closes the block.
            $safe = preg_replace('#</(script)#i', '<\/$1', $jsonld);
            echo "\n<!-- SEO Tool: schema -->\n<script type=\"application/ld+json\">"
                . $safe
                . "</script>\n";
        }
    }
});

function stb_rest_list_posts(WP_REST_Request $req): WP_REST_Response
{
    $type = sanitize_key($req->get_param('type') ?? 'post');
    $limit = (int)($req->get_param('limit') ?? 50);
    $limit = max(1, min(200, $limit));

    $posts = get_posts([
        'post_type' => $type,
        'post_status' => 'publish',
        'numberposts' => $limit,
        'orderby' => 'modified',
        'order' => 'DESC',
    ]);

    return new WP_REST_Response([
        'ok' => true,
        'count' => count($posts),
        'posts' => array_map(function ($p) {
            return [
                'id' => $p->ID,
                'title' => $p->post_title,
                'permalink' => get_permalink($p->ID),
                'modified' => $p->post_modified,
                'meta_description' => stb_get_meta_description($p->ID),
            ];
        }, $posts),
    ]);
}

