add_action('rest_api_init', function () {
    register_rest_route(STB_REST_NAMESPACE, '/ping', [
        'methods'  => 'GET',
        'callback' => 'stb_rest_ping',
        'permission_callback' => 'stb_check_key',
    ]);

    // Single route, two methods. Calling register_rest_route twice with
    // the same path made WP's REST router behavior depend on call order
    // — the second call would shadow the first, breaking GET. Passing
    // an array of method configs is the documented WP way.
    register_rest_route(STB_REST_NAMESPACE, '/post/(?P<id>\d+)/seo', [
        [
            'methods'  => 'GET',
            'callback' => 'stb_rest_get_post_seo',
            'permission_callback' => 'stb_check_key',
            'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
        ],
        [
            'methods'  => 'POST',
            'callback' => 'stb_rest_update_post_seo',
            'permission_callback' => 'stb_check_key',
            'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
        ],
    ]);

    register_rest_route(STB_REST_NAMESPACE, '/attachment/(?P<id>\d+)/alt', [
        'methods'  => 'POST',
        'callback' => 'stb_rest_update_alt',
        'permission_callback' => 'stb_check_key',
        'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
    ]);

    // GET added in 0.3.0. Without a read, the SEO Tool could only write
    // schema to pages that had none — writing to a page with existing
    // markup would destroy hand-written structured data with no way back,
    // so the tool refused to try. Reading first makes updates safe.
    register_rest_route(STB_REST_NAMESPACE, '/post/(?P<id>\d+)/schema', [
        [
            'methods'  => 'GET',
            'callback' => 'stb_rest_get_schema',
            'permission_callback' => 'stb_check_key',
            'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
        ],
        [
            'methods'  => 'POST',
            'callback' => 'stb_rest_set_schema',
            'permission_callback' => 'stb_check_key',
            'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
        ],
    ]);

    // 0.3.0 — the images on a post, WITH their attachment ids.
    //
    // /attachment/{id}/alt has always existed, but nothing could work out
    // which attachment an image on a page belonged to: an audit finding
    // gives a page URL and an <img src>, not an id. So the SEO Tool could
    // find images missing alt text and never fix one. This closes that.
    register_rest_route(STB_REST_NAMESPACE, '/post/(?P<id>\d+)/images', [
        'methods'  => 'GET',
        'callback' => 'stb_rest_list_post_images',
        'permission_callback' => 'stb_check_key',
        'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
    ]);

    // 0.3.0 — insert internal links into post content.
    //
    // This is the only endpoint that edits the post BODY rather than a
    // metadata field, which makes it a different risk class: a bad write
    // damages the article itself. Three guards, all in the handler:
    // anchors are matched only in visible text (never inside an existing
    // tag or link), the first occurrence only, and the whole prior
    // post_content is stored as the revision so undo is exact.
    register_rest_route(STB_REST_NAMESPACE, '/post/(?P<id>\d+)/links', [
        'methods'  => 'POST',
        'callback' => 'stb_rest_insert_links',
        'permission_callback' => 'stb_check_key',
        'args' => ['id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
    ]);

    register_rest_route(STB_REST_NAMESPACE, '/posts/list', [
        'methods'  => 'GET',
        'callback' => 'stb_rest_list_posts',
        'permission_callback' => 'stb_check_key',
    ]);

    // Resolve a public URL to a post ID. Used by the SEO Tool's
    // one-click fix flow so users only need a URL, not the post ID.
    register_rest_route(STB_REST_NAMESPACE, '/find', [
        'methods'  => 'GET',
        'callback' => 'stb_rest_find_by_url',
        'permission_callback' => 'stb_check_key',
        'args' => ['url' => ['validate_callback' => fn($v) => is_string($v) && strlen($v) > 3]],
    ]);

    register_rest_route(STB_REST_NAMESPACE, '/revisions', [
        'methods'  => 'GET',
        'callback' => 'stb_rest_revisions',
        'permission_callback' => 'stb_check_key',
    ]);

    // Site-level surfaces. One shape for all three: GET reads the
    // current value, POST replaces it. Kept apart from the post routes
    // because the blast radius is the whole site rather than one page —
    // a wrong line in robots.txt can deindex everything — which is why
    // the client marks all three needs_review whatever the autonomy
    // level says.
    register_rest_route(STB_REST_NAMESPACE, '/site/robots', [
        [
            'methods'  => 'GET',
            'callback' => 'stb_rest_get_robots_txt',
            'permission_callback' => 'stb_check_key',
        ],
        [
            'methods'  => 'POST',
            'callback' => 'stb_rest_set_robots_txt',
            'permission_callback' => 'stb_check_key',
        ],
    ]);

    register_rest_route(STB_REST_NAMESPACE, '/site/redirects', [
        [
            'methods'  => 'GET',
            'callback' => 'stb_rest_get_redirects',
            'permission_callback' => 'stb_check_key',
        ],
        [
            'methods'  => 'POST',
            'callback' => 'stb_rest_set_redirects',
            'permission_callback' => 'stb_check_key',
        ],
    ]);

    register_rest_route(STB_REST_NAMESPACE, '/site/hardening', [
        [
            'methods'  => 'GET',
            'callback' => 'stb_rest_get_hardening',
            'permission_callback' => 'stb_check_key',
        ],
        [
            'methods'  => 'POST',
            'callback' => 'stb_rest_set_hardening',
            'permission_callback' => 'stb_check_key',
        ],
    ]);

    register_rest_route(STB_REST_NAMESPACE, '/undo/(?P<rev_id>\d+)', [
        'methods'  => 'POST',
        'callback' => 'stb_rest_undo',
        'permission_callback' => 'stb_check_key',
        'args' => ['rev_id' => ['validate_callback' => static fn($v) => is_numeric($v)]],
    ]);

    // v0.2.0+ — create a post. Used by daily automation when a blog_draft
    // queue item is approved + published. Status defaults to "draft" so
    // the WP editor gets a final pass before going live; schedules with
    // auto_publish=true pass "publish" to skip that.
    register_rest_route(STB_REST_NAMESPACE, '/posts', [
        'methods'  => 'POST',
        'callback' => 'stb_rest_create_post',
        'permission_callback' => 'stb_check_key',
    ]);
});

/**
 * Authenticate an inbound request against the connection key.
 *
 * Accepts the key in EITHER header:
 *
 *   X-STB-Key: <key>                 preferred
 *   Authorization: Bearer <key>      also accepted
 *
 * This only read `Authorization`, and the SEO Tool has only ever sent
 * `X-STB-Key` — so every request from the tool to this plugin returned
 * 401, for every endpoint, for the plugin's entire life. Nothing about
 * the failure said "wrong header": a 401 reads as a bad key, which is
 * what anyone debugging it would have chased.
 *
 * X-STB-Key is preferred rather than merely tolerated, because Apache
 * with mod_php commonly drops the Authorization header before PHP sees
 * it unless the site owner adds a rewrite rule. A custom header has no
 * such problem, so the tool's choice was the better one. Bearer stays
 * supported for anything already built against the documented form.
 *
 * hash_equals is timing-safe; the length check in front of it is not a
 * security property, just an early out.
 */
function stb_check_key(WP_REST_Request $req): bool
{
    $expected = get_option(STB_OPTION_KEY);
    if (!is_string($expected) || $expected === '') {
        return false;
    }

    $custom = trim((string)($req->get_header('x-stb-key') ?? ''));
    if ($custom !== '' && hash_equals($expected, $custom)) {
        return true;
    }

    $auth = (string)($req->get_header('authorization') ?? '');
    if ($auth === '') {
        return false;
    }
    $bearer = trim((string)preg_replace('/^Bearer\s+/i', '', $auth));
    return $bearer !== '' && hash_equals($expected, $bearer);
}

